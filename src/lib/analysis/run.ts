import "server-only";
import type { Analysis } from "@/types";
import { getStore } from "@/lib/db";
import { getCoach } from "@/lib/coaches/data";
import { env } from "@/lib/env";
import { generateMockAnalysis } from "./engine";
import { generateLlmAnalysis } from "@/lib/llm";
import { attachCheckpointFrames } from "@/lib/media/ffmpeg";

/**
 * Analysis pipeline entry point.
 * Order: pose service (if configured) -> LLM (if configured) -> mock engine.
 * Always returns an Analysis; never throws for missing services.
 */
export async function runAnalysis(swingId: string): Promise<Analysis> {
  const store = getStore();
  const swing = await store.getSwing(swingId);
  if (!swing) throw new Error("Swing not found");
  const coach = getCoach(swing.coachId) ?? getCoach("michaelSchrempf")!;

  let poseSummary = "No pose service configured; using golfer-reported context.";
  if (env.pose.enabled) {
    try {
      const res = await fetch(`${env.pose.url}/analyze`, { method: "POST", body: JSON.stringify({ swingId }), cache: "no-store" });
      if (res.ok) poseSummary = JSON.stringify(await res.json()).slice(0, 4000);
    } catch { /* optional service: fall through */ }
  }

  if (env.llm.enabled) {
    try {
      const analysis = await generateLlmAnalysis(swing, coach, poseSummary);
      const withFrames = await attachCheckpointFrames(swing, analysis);
      return { ...withFrames, disclaimer: analysis.disclaimer || "Generated by the configured LLM coach." };
    } catch (e) {
      console.warn("[analysis] LLM failed, falling back to mock engine:", e);
    }
  }

  return attachCheckpointFrames(swing, generateMockAnalysis(swing, coach));
}
